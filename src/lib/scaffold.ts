export const getTarget = (id: string) => TARGETS.find((t) => t.id === id) ?? TARGETS[0];

/** The delimiter convention the model writes files in.
 *
 *  Chosen over JSON deliberately: asking a model to JSON-escape hundreds of
 *  lines of code reliably produces broken escapes, whereas a line-based
 *  delimiter survives any content. */
export const FILE_FORMAT = `Return every file using this exact format, and nothing else:

=== path/to/file.ext ===
<the complete file contents>
=== another/file.ext ===
<the complete file contents>

Rules: no prose before, between or after. No markdown fences. Paths are relative with forward slashes. Write each file in full — never abbreviate with "..." or "rest unchanged".`;

/** Parse the delimiter format back into files. */
export function parseProjectFiles(text: string): ProjectFile[] {
  const out: ProjectFile[] = [];
  // Tolerate a stray fence around the whole reply, which models sometimes add.
  const body = text.replace(/^\s*```[\w-]*\s*\n/, "").replace(/\n```\s*$/, "");
  const re = /^===\s*(.+?)\s*===\s*$/gm;
  const marks: Array<{ path: string; start: number; end: number }> = [];
  let m: RegExpExecArray | null;
  while ((m = re.exec(body))) marks.push({ path: m[1].trim(), start: m.index, end: re.lastIndex });

  for (let i = 0; i < marks.length; i++) {
    const content = body.slice(marks[i].end, i + 1 < marks.length ? marks[i + 1].start : undefined);
    const path = marks[i].path
      .replace(/\\/g, "/")
      .replace(/\/{2,}/g, "/")   // a Windows-style path can collapse to doubles
      .replace(/^\/+/, "");
    // Guard against a model writing a path that escapes the project root.
    if (!path || path.includes("..")) continue;
    out.push({ path, content: content.replace(/^\n/, "").replace(/\s*$/, "\n") });
  }
  return out;
}

/** Merge generated files over the base scaffold; generated wins on conflict. */
export function mergeProject(base: ProjectFile[], generated: ProjectFile[]): ProjectFile[] {
  const map = new Map(base.map((f) => [f.path, f]));
  for (const g of generated) map.set(g.path, g);
  return [...map.values()].sort((a, b) => a.path.localeCompare(b.path));
}
