/* ────────────────────────────────────────────────────────────────────────────
   Project targets.

   A single HTML file is a fine way to make something in five minutes and a
   poor way to keep it. These targets let Studio emit a real project — one you
   can `npm install` and open in an editor — rather than only a document.

   Each target carries a base scaffold that is correct on its own: package.json,
   config, entry points, a README. The model fills in the parts that are
   actually about your idea. That split matters, because models are good at
   application code and unreliable at remembering whether Vite wants
   `"type": "module"` — and a project that fails on first `npm run dev` is
   worse than no project.
   ──────────────────────────────────────────────────────────────────────────── */

export interface ProjectFile {
  path: string;
  content: string;
}

export interface Target {
  id: string;
  name: string;
  blurb: string;
  /** What the model is told to produce, on top of the base files. */
  brief: string;
  /** Files that are always correct and never generated. */
  base: (name: string) => ProjectFile[];
  /** Paths the model is expected to write. */
  expects: string[];
  run: string;
}

